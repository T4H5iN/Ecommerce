    private void jButton22ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton22ActionPerformed
        int selectedRow = jTable1.getSelectedRow();
        String username = usernameField.getText();
        String itemName = (String) jTable1.getValueAt(selectedRow, 1);
        String comment = commentBox.getText();

        try {
            Connection connection = DriverManager.getConnection("jdbc:mysql://localhost:3306/credentials", "root", "tahsin");
            String query = "INSERT INTO comments (Username, itemName, comment) VALUES (?, ?, ?)";
            PreparedStatement preparedStatement = connection.prepareStatement(query);
            preparedStatement.setString(1, username);
            preparedStatement.setString(2, itemName);
            preparedStatement.setString(3, comment);
            int rowsInserted = preparedStatement.executeUpdate();

            if (rowsInserted > 0) {
                commentDialog.setVisible(true);
            }

            preparedStatement.close();
            connection.close();
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
    }//GEN-LAST:event_jButton22ActionPerformed

