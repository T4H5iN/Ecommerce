    private void commentsButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_commentsButtonActionPerformed
        homePage.setVisible(false);
        updateProfile.setVisible(false);
        purchaseHistory.setVisible(false);
        commentsPage.setVisible(true);

        String username = usernameField.getText();
        DefaultTableModel model = (DefaultTableModel) jTable6.getModel();
        model.setRowCount(0);

        try {
            Connection connection = DriverManager.getConnection("jdbc:mysql://localhost:3306/credentials", "root", "tahsin");
            String query = "SELECT itemName,comment FROM comments WHERE Username = ?";
            PreparedStatement preparedStatement = connection.prepareStatement(query);
            preparedStatement.setString(1, username);
            ResultSet resultSet = preparedStatement.executeQuery();

            while (resultSet.next()) {
                String name = resultSet.getString("itemName");
                String comm = resultSet.getString("comment");

                Object[] rowData = {name, comm};

                model.addRow(rowData);
            }

            resultSet.close();
            preparedStatement.close();
            connection.close();
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
    }//GEN-LAST:event_commentsButtonActionPerformed

