    private void addCartButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addCartButtonActionPerformed
        String jdbcUrl = "jdbc:mysql://localhost:3306/shop";
        String username = "root";
        String password = "tahsin";

        try {
            Connection connection = DriverManager.getConnection(jdbcUrl, username, password);

            int selectedRow = jTable1.getSelectedRow();
            if (selectedRow != -1) {
                String quantityText = jTextField1.getText();

                if (!quantityText.isEmpty()) {
                    try {
                        int quantity = Integer.parseInt(quantityText);
                        if (quantity > 0) {
                            String itemName = (String) jTable1.getValueAt(selectedRow, 1);
                            int itemPrice = (int) jTable1.getValueAt(selectedRow, 2);

                            String selectQuery = "SELECT Quantity FROM shop.shopitems WHERE Name = ?";
                            PreparedStatement selectStatement = connection.prepareStatement(selectQuery);
                            selectStatement.setString(1, itemName);
                            ResultSet resultSet = selectStatement.executeQuery();

                            if (resultSet.next()) {
                                int availableQuantity = resultSet.getInt("Quantity");

                                if (quantity <= availableQuantity) {
                                    String updateQuery = "UPDATE shop.shopitems SET Quantity = ? WHERE Name = ?";
                                    PreparedStatement updateStatement = connection.prepareStatement(updateQuery);
                                    updateStatement.setInt(1, availableQuantity - quantity);
                                    updateStatement.setString(2, itemName);
                                    updateStatement.executeUpdate();

                                    int currentTotal = Integer.parseInt(jTextField9.getText().replace(" BDT", ""));
                                    int newTotal = currentTotal + (itemPrice * quantity);

                                    jTextField9.setText(newTotal + " BDT");

                                    jTextField26.setText("" + i++);

                                    DefaultTableModel secondTableModel = (DefaultTableModel) jTable3.getModel();
                                    secondTableModel.addRow(new Object[]{itemName, itemPrice, quantity, itemPrice * quantity});

                                    int currentgrandTotal = Integer.parseInt(jTextField30.getText().replace(" BDT", ""));
                                    int newgrandTotal = currentgrandTotal + (itemPrice * quantity);

                                    jTextField30.setText(newgrandTotal + " BDT");
                                    jTextField1.setText("1");
                                    
                                    updateStatement.close();
                                } else {
                                    // Display an error message for insufficient quantity
                                    insufficientQuantityDialog.setVisible(true);

                                }
                            } else {
                                System.err.println("Item not found in database: " + itemName);
                            }

                            resultSet.close();
                            selectStatement.close();

                        } else {
                            // Display an error message for non-positive quantity
                            quantityDialog.setVisible(true);
                        }
                    } catch (NumberFormatException e) {
                        // Display an error message for invalid quantity
                        quantityDialog.setVisible(true);
                    }
                } else {
                    // Display an error message for an empty quantity
                    quantityDialog.setVisible(true);
                }
            }else{
                addCartDialog.setVisible(true);
            }
            connection.close();
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_addCartButtonActionPerformed

