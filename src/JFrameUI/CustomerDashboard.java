        String username = usernameField.getText();
        DefaultTableModel model = (DefaultTableModel) jTable5.getModel();
        model.setRowCount(0);

        try {
            Connection connection = DriverManager.getConnection("jdbc:mysql://localhost:3306/credentials", "root", "tahsin");
            String query = "SELECT purchaseID,totalAmount,dateOfPurchase FROM purchasehistory WHERE username = ?";
            PreparedStatement preparedStatement = connection.prepareStatement(query);
            preparedStatement.setString(1, username);
            ResultSet resultSet = preparedStatement.executeQuery();

            while (resultSet.next()) {
                int purchaseID = resultSet.getInt("purchaseID");
                String totalPrice = resultSet.getString("totalAmount");
                Date purchaseDate = resultSet.getDate("dateOfPurchase");

                Object[] rowData = {purchaseID, totalPrice, purchaseDate};

                model.addRow(rowData);
            }

            resultSet.close();
            preparedStatement.close();
            connection.close();
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
